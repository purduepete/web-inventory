using SixLabors.ImageSharp;
using SixLabors.ImageSharp.Formats.Jpeg;
using SixLabors.ImageSharp.Processing;

namespace WebInventory.Api.Services;

public sealed class BlobService
{
    public string Root { get; }
    public bool Enabled => true;

    public BlobService()
    {
        var configured = Environment.GetEnvironmentVariable("ImageDirectory")
            ?? throw new InvalidOperationException("ImageDirectory is required.");
        if (!Path.IsPathFullyQualified(configured))
            throw new InvalidOperationException("ImageDirectory must be an absolute directory.");
        Root = Path.GetFullPath(configured);
        if (!Directory.Exists(Root))
            throw new InvalidOperationException("ImageDirectory must be an existing absolute directory.");
    }

    private string PathFor(string url)
    {
        // Only identifiers generated by this app can become filesystem paths.
        var match = System.Text.RegularExpressions.Regex.Match(url,
            @"^/images/([0-9a-fA-F-]{36})/([0-9a-fA-F-]{36})(_thumb)?\.jpg$");
        if (!match.Success || !Guid.TryParse(match.Groups[1].Value, out var container) ||
            !Guid.TryParse(match.Groups[2].Value, out var photo))
            throw new ArgumentException("Invalid local image URL.", nameof(url));
        return Path.Combine(Root, container.ToString(), photo + match.Groups[3].Value + ".jpg");
    }

    private static string Url(Guid containerId, Guid photoId, bool thumbnail = false)
        => $"/images/{containerId}/{photoId}{(thumbnail ? "_thumb" : "")}.jpg";

    private async Task WriteAsync(string url, byte[] bytes, CancellationToken ct)
    {
        var path = PathFor(url);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            await File.WriteAllBytesAsync(temporary, bytes, ct);
            File.Move(temporary, path, overwrite: true);
        }
        finally
        {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
    }

    public async Task<(string blobUrl, string thumbUrl)> UploadAsync(
        Guid containerId, Guid photoId, byte[] bytes, CancellationToken ct)
    {
        using var image = Image.Load(bytes);
        var full = Url(containerId, photoId);
        var thumb = Url(containerId, photoId, true);
        var thumbnail = await ThumbnailAsync(image, ct);
        await WriteAsync(full, bytes, ct);
        await WriteAsync(thumb, thumbnail, ct);
        return (full, thumb);
    }

    private static async Task<byte[]> ThumbnailAsync(Image image, CancellationToken ct)
    {
        using var thumbnail = image.Clone(x => x.Resize(new ResizeOptions { Mode = ResizeMode.Max, Size = new Size(320, 320) }));
        using var output = new MemoryStream();
        await thumbnail.SaveAsJpegAsync(output, new JpegEncoder { Quality = 70 }, ct);
        return output.ToArray();
    }

    public async Task<string?> RegenerateThumbnailAsync(
        Guid containerId, Guid photoId, string fullBlobUrl, CancellationToken ct)
    {
        using var image = await Image.LoadAsync(PathFor(fullBlobUrl), ct);
        var url = Url(containerId, photoId, true);
        await WriteAsync(url, await ThumbnailAsync(image, ct), ct);
        return url;
    }

    public async Task<string?> RotateAsync(
        Guid containerId, Guid photoId, string fullBlobUrl, int degrees, CancellationToken ct)
    {
        using var image = await Image.LoadAsync(PathFor(fullBlobUrl), ct);
        image.Mutate(x => x.Rotate(degrees));
        using var output = new MemoryStream();
        await image.SaveAsJpegAsync(output, new JpegEncoder { Quality = 85 }, ct);
        await WriteAsync(fullBlobUrl, output.ToArray(), ct);
        var thumb = Url(containerId, photoId, true);
        await WriteAsync(thumb, await ThumbnailAsync(image, ct), ct);
        return thumb;
    }

    public Task DeleteAsync(string blobUrl, CancellationToken ct)
    {
        ct.ThrowIfCancellationRequested();
        File.Delete(PathFor(blobUrl));
        return Task.CompletedTask;
    }

    public Task<string> SignReadUrlAsync(string blobUrl, CancellationToken ct)
    {
        ct.ThrowIfCancellationRequested();
        _ = PathFor(blobUrl);
        return Task.FromResult(blobUrl);
    }
}
